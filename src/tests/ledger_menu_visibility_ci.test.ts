/* Regressão M240: Livro-Razão deve existir no menu do Admin, sem exposição financeira Master/Membro. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {tabsAllowedToRole,isRoleTabAllowed} from '../services/roleScope';
const file=readFileSync('src/App.tsx','utf8');
const adminStart=file.indexOf("if (state.currentRole === 'TENANT_ADMIN') {");
const memberStart=file.indexOf("// TENANT_MEMBER",adminStart);
assert(adminStart>=0&&memberStart>adminStart,'Navegação administrativa não encontrada');
const adminMenu=file.slice(adminStart,memberStart);
assert.match(adminMenu,/\{ id: 'LEDGER', label: 'Livro-Razão', icon: FileSpreadsheet \}/);
assert(adminMenu.includes("id: 'EMPRESTIMOS'")&&adminMenu.includes("id: 'FECHAMENTO'"));
assert.equal(tabsAllowedToRole('TENANT_ADMIN').filter(x=>x==='LEDGER').length,1);
assert.equal(isRoleTabAllowed('TENANT_ADMIN','LEDGER'),true);
assert.equal(isRoleTabAllowed('MASTER','LEDGER'),false);
assert.equal(isRoleTabAllowed('TENANT_MEMBER','LEDGER'),false);
assert(!tabsAllowedToRole('MASTER').includes('LEDGER'));
assert(!tabsAllowedToRole('TENANT_MEMBER').includes('LEDGER'));
assert.match(file,/visibleTab === 'LEDGER' && <LedgerView state=\{state\} \/>/);
assert.match(file,/navItems\.slice\(3\)\.map\(item =>/);
assert.match(file,/navItems\.map\(item =>/);
assert.match(file,/const visibleTab = isRoleTabAllowed\(state\.currentRole, activeTab\)/);
const view=readFileSync('src/components/LedgerView.tsx','utf8');
assert.match(view,/state\.currentRole !== 'TENANT_ADMIN'/);
assert.match(view,/fetchLedgerIntegrityPreview\(state\.currentTenantId\)/);
assert.match(view,/integrity\.status!=='BALANCED'/);
assert.match(view,/authService\.isSessionSnapshotCurrent\(snapshot\)/);
const api=readFileSync('src/services/financialApiService.ts','utf8');
assert.match(api,/assertLedgerAdmin\(tenantId\)/);
console.log('LIVRO_RAZAO_MENU_APK_ADMIN_ONLY=PASS');
