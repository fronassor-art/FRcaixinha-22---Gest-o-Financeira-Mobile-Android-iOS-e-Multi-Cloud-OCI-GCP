import assert from 'node:assert/strict';
import {startTabHistory,visitTab,stepTab,canStepTab} from '../services/tabHistory';
import {isRoleTabAllowed} from '../services/roleScope';
const master=(s:string)=>isRoleTabAllowed('MASTER',s);
const member=(s:string)=>isRoleTabAllowed('TENANT_MEMBER',s);
let h=startTabHistory('DASHBOARD');
h=visitTab(h,'CAIXINHAS',master);
h=visitTab(h,'LICENCAS',master);
assert.equal(h.index,2);
assert.equal(canStepTab(h,1),false);
h=stepTab(h,-1);
assert.equal(h.entries[h.index],'CAIXINHAS');
assert.equal(canStepTab(h,1),true);
h=visitTab(h,'SUPORTE',master);
assert.deepEqual(h.entries,['DASHBOARD','CAIXINHAS','SUPORTE']);
assert.equal(stepTab(h,1),h);
assert.equal(visitTab(h,'MEU_EMPRESTIMO',master),h);
h=startTabHistory('MEU_PAINEL');
h=visitTab(h,'MINHAS_CONTRIBUICOES',member);
assert.equal(visitTab(h,'LICENCAS',member),h);
h=stepTab(h,-1);
assert.equal(h.entries[h.index],'MEU_PAINEL');
let bounded=startTabHistory('DASHBOARD');
for(let i=0;i<75;i++)bounded=visitTab(bounded,i%2?'CAIXINHAS':'LICENCAS',master);
assert(bounded.entries.length<=24);
console.log('M20300_HISTORY_ROLE_SCOPED=PASS');
